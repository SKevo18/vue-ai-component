export const messages: Record<Locale, Messages> = { en, sk };

function merge<T>(base: T, over: unknown): T {
  if (!over || typeof over !== "object") return base;
  const out = { ...base } as Record<string, unknown>;
  for (const [k, v] of Object.entries(over as Record<string, unknown>)) {
    const current = out[k];
    out[k] = current && typeof current === "object" && v && typeof v === "object" ? merge(current, v) : (v ?? current);
  }
  return out as T;
}

export type Translate = (key: string, params?: Record<string, string | number>) => string;

export function createTranslator(locale: MaybeRefOrGetter<Locale | string | undefined>, overrides: Partial<Record<Locale, MessageOverrides>> = {}): { t: Translate; locale: () => Locale } {
  const current = computed<Locale>(() => (toValue(locale) === "sk" ? "sk" : "en"));
  const table = computed(() => merge(messages[current.value], overrides[current.value]));
  const t: Translate = (key, params) => {
    let value: unknown = table.value;
    for (const part of key.split(".")) value = value && typeof value === "object" ? (value as Record<string, unknown>)[part] : undefined;
    const text = typeof value === "string" ? value : key;
    return params ? text.replace(/\{(\w+)\}/g, (m, name: string) => (params[name] !== undefined ? String(params[name]) : m)) : text;
  };
  return { t, locale: () => current.value };
}
